// A feed is a frozen specification that clients read from at any position. Nothing is
// stored but the specification: a record is a function of its position, so a read
// generates what it asks for, and every client sees the same bytes.

// CodeFeedEngine marks a feed made by another engine version, whose bytes this binary
// cannot reproduce.
const CodeFeedEngine = "ERR_FEED_ENGINE"

// FeedStream is one stream of a feed, as clients need to know it.
type FeedStream struct {
	ID string `json:"id"`
	// End is one past the last position, 0 if the stream has no end.
	End uint64 `json:"end,omitempty"`
	// Dense says every position holds a record, so counting records gives the position.
	Dense bool `json:"dense"`
}

// FeedStreams lists an engine's streams for storing with a feed.
func FeedStreams(streams []gen.StreamSpec) []FeedStream {
	out := make([]FeedStream, len(streams))
	for i, s := range streams {
		out[i] = FeedStream{ID: string(s.ID), End: s.Space, Dense: s.PerParent == 1}
	}
	return out
}

// feedProblems refuses what a specification may say that means nothing for a feed, rather
// than silently ignoring it.
func feedProblems(spec *Spec) []apperr.Problem {
	var out []apperr.Problem
	refuse := func(path, why string) {
		out = append(out, apperr.Problem{Path: path, Code: "ERR_BAD_VALUE", Message: why})
	}
	const noRun = "a feed has no run: reads generate what they ask for"
	if spec.Kind != "" && spec.Kind != "Feed" {
		refuse("kind", "want Feed")
	}
	if spec.Mode != "" && spec.Mode != ModeStream {
		refuse("mode", "a feed has no mode: leave it out")
	}
	if spec.Limits.Duration != 0 {
		refuse("limits.duration", noRun)
	}
	if spec.Limits.MaxBytes != 0 {
		refuse("limits.max_bytes", noRun)
	}
	if spec.Limits.MaxWorkers != 0 {
		refuse("limits.max_workers", "feeds are generated by the Coordinator, not Workers")
	}
	if spec.Execution.UnitRecords != 0 {
		refuse("execution.unit_records", noRun)
	}
	if len(spec.Execution.WorkerSelector) != 0 {
		refuse("execution.worker_selector", "feeds are generated by the Coordinator, not Workers")
	}
	if spec.Execution.Debug {
		refuse("execution.debug", noRun)
	}
	if spec.Output.Compression != "" && spec.Output.Compression != "none" {
		refuse("output.compression", "feeds are not compressed; use HTTP compression in front if needed")
	}
	if spec.Output.PartMaxBytes != "" {
		refuse("output.part_max_bytes", "a feed has no parts")
	}
	if spec.Output.PartMaxRecords != 0 {
		refuse("output.part_max_records", "a feed has no parts")
	}
	if spec.Output.PartMaxAge != 0 {
		refuse("output.part_max_age", "a feed has no parts")
	}
	if spec.Retention.Pin {
		refuse("retention.pin", "a feed stores no output")
	}
	return out
}

// CreateFeed validates a specification and freezes it as a feed.
func (s *Service) CreateFeed(ctx context.Context, data []byte, actor string) (*store.Feed, error) {
	spec, err := ParseSpec(data)
	if err != nil {
		return nil, err
	}
	if problems := feedProblems(spec); len(problems) > 0 {
		return nil, apperr.Validation(CodeValidation, "invalid feed specification", problems)
	}
	spec.Kind, spec.Mode = "", ModeStream
	seed, err := chooseSeed()
	if err != nil {
		return nil, err
	}
	c, err := Compile(spec, s.Config, resolver{ctx, s}, s.Vocab, seed, s.Clock.Now())
	if err != nil {
		return nil, err
	}
	compiled, err := c.Snapshot.Compile(s.Vocab)
	if err != nil {
		return nil, err
	}
	streams, err := json.Marshal(FeedStreams(compiled.Engine.Streams()))
	if err != nil {
		return nil, err
	}
	hash, body, err := c.Snapshot.Encode()
	if err != nil {
		return nil, err
	}
	now := s.Clock.Now()
	row := &store.Feed{
		ID: ids.New("fed"), Name: spec.Name, Description: spec.Description, Strategy: c.Strategy, Format: c.Snapshot.Format,
		SnapshotHash: hash, Seed: c.Snapshot.Seed, ReferenceTime: c.Snapshot.ReferenceTime, EngineVersion: c.Snapshot.EngineVersion,
		Rate: spec.Limits.Rate, StreamsJSON: string(streams), CreatedAt: now, CreatedBy: actor,
	}
	err = s.DB.Write(ctx, func(ctx context.Context, tx store.Tx) error {
		if err := tx.PutSnapshot(ctx, hash, c.Snapshot.EngineVersion, body, now); err != nil {
			return err
		}
		return tx.InsertFeed(ctx, row)
	})
	if err != nil {
		return nil, err
	}
	return row, nil
}

// GetFeed reads a feed.
func (s *Service) GetFeed(ctx context.Context, id string) (*store.Feed, error) {
	var row *store.Feed
	err := s.DB.Read(ctx, func(ctx context.Context, tx store.Tx) error {
		var err error
		row, err = tx.GetFeed(ctx, id)
		return err
	})
	if errors.Is(err, store.ErrNotFound) {
		return nil, apperr.New(apperr.NotFound, CodeNotFound, "no feed "+id)
	}
	return row, err
}

// ListFeeds lists feeds in ID order.
func (s *Service) ListFeeds(ctx context.Context, after string, limit int) ([]store.Feed, error) {
	var rows []store.Feed
	err := s.DB.Read(ctx, func(ctx context.Context, tx store.Tx) error {
		var err error
		rows, err = tx.ListFeeds(ctx, after, limit)
		return err
	})
	return rows, err
}

// DeleteFeed removes a feed. Reads in progress finish; they already have what they need.
func (s *Service) DeleteFeed(ctx context.Context, id string) error {
	if _, err := s.GetFeed(ctx, id); err != nil {
		return err
	}
	return s.DB.Write(ctx, func(ctx context.Context, tx store.Tx) error { return tx.DeleteFeed(ctx, id) })
}

// CompileFeed loads a feed's snapshot, ready to generate from.
func (s *Service) CompileFeed(ctx context.Context, row *store.Feed) (*snapshot.Compiled, error) {
	if row.EngineVersion != gen.Version {
		return nil, apperr.New(apperr.Conflict, CodeFeedEngine, fmt.Sprintf("this feed needs engine version %d and this binary has %d: create a new feed", row.EngineVersion, gen.Version))
	}
	snap, err := s.LoadSnapshot(ctx, row.SnapshotHash)
	if err != nil {
		return nil, err
	}
	return snap.Compile(s.Vocab)
}
